import Foundation

/// Lightweight in-app localisation. UI strings are written in English and looked up here, so the
/// language can be switched inside the app (Settings ▸ Advanced ▸ Language) without a restart.
enum Lang {
    nonisolated(unsafe) private(set) static var isTurkish = Lang.systemPrefersTurkish

    static var systemPrefersTurkish: Bool {
        Locale.preferredLanguages.first?.lowercased().hasPrefix("tr") ?? false
    }

    static func apply(_ language: AppLanguage) {
        switch language {
        case .system: isTurkish = systemPrefersTurkish
        case .english: isTurkish = false
        case .turkish: isTurkish = true
        }
    }

    static var locale: Locale { Locale(identifier: isTurkish ? "tr_TR" : "en_US") }
}

/// Returns the UI string in the current language.
func L(_ key: String) -> String {
    if Lang.isTurkish, let t = turkish[key] { return t }
    return english[key] ?? key
}

